TEST_TICKERS = [t for t, _ in US_TICKERS + EUROPE_TICKERS]

BATCH_SIZE = 40


def store_test_prices(conn: sqlite3.Connection, df: pd.DataFrame) -> int:
    """Kurse eines Tickers ersetzen (ganze Historie). Caller committet."""
    if df.empty:
        return 0
    conn.execute("DELETE FROM test_prices WHERE ticker=?", (df["ticker"].iloc[0],))
    conn.executemany(
        "INSERT INTO test_prices (ticker, date, open, high, low, close) VALUES (?,?,?,?,?,?)",
        [(r.ticker, r.date, float(r.open), float(r.high), float(r.low), float(r.close))
         for r in df.itertuples(index=False)],
    )
    return len(df)


def load_test_prices(conn: sqlite3.Connection, tickers: list[str] | None = None,
                     only_missing: bool = True) -> dict:
    """Lädt HISTORY_DAYS Kurshistorie für das Test-Universum in test_prices.
    only_missing=True überspringt Ticker, die schon Kurse haben. Committet je
    Batch. Gibt {loaded, empty, skipped} zurück."""
    from src.fetchers.stock_fetcher import fetch_prices_batch, HISTORY_DAYS

    tickers = tickers or TEST_TICKERS
    watch = {r[0] for r in conn.execute("SELECT ticker FROM watchlist")}
    have = {r[0] for r in conn.execute("SELECT DISTINCT ticker FROM test_prices")} if only_missing else set()
    todo = [t for t in tickers if t not in watch and t not in have]
    out = {"loaded": 0, "empty": [], "skipped": len(tickers) - len(todo)}
    for i in range(0, len(todo), BATCH_SIZE):
        chunk = todo[i:i + BATCH_SIZE]
        results = fetch_prices_batch(chunk, days=HISTORY_DAYS)
        for t in chunk:
            df = results.get(t, pd.DataFrame())
            if df.empty:
                out["empty"].append(t)
                continue
            store_test_prices(conn, df)
            out["loaded"] += 1
        conn.commit()
        print(f"  {min(i + BATCH_SIZE, len(todo))}/{len(todo)} Ticker geladen …")
        time.sleep(0.3)
    return out
